import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await (await b.newContext({viewport:{width:1440,height:900},deviceScaleFactor:2,locale:"zh-CN"})).newPage();
await p.goto("http://127.0.0.1:8080/comic/unread", {waitUntil:"domcontentloaded"});
await p.waitForTimeout(2500);
await p.locator('[data-testid="album-card"]').nth(1).hover();
await p.waitForTimeout(800);
await p.screenshot({path:"../.smoke/hovercard-r15.png", clip:{x:460,y:290,width:400,height:280}});
console.log("ok");
await b.close();
